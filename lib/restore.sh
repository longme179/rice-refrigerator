# lib/restore.sh - package reinstallation and /etc planning for rice-restore (rule R9).
# Sourced by bin/rice-restore.sh. NOTHING in this file executes a package
# manager or sudo: it only generates reviewable scripts and lists. Cross-distro
# package names use a small explicit alias table (DECISIONS D8); everything
# without a mapping is LISTED in UNMAPPED.txt, never guessed.

# "backup-name|target-name" pairs - deliberately tiny and explicit
RICE_XDISTRO_ALIASES=(
  'vim-enhanced|vim'
  'vim-X11|vim'
  'gvim|vim'
  'google-chrome-stable|google-chrome'
  'network-manager|networkmanager'
  'NetworkManager|networkmanager'
  'python3-dnf|dnf'
  'python3-pip|python-pip'
)

rice_xdistro_map() { # $1 package name -> mapped name, or nothing
  local p=$1 a
  for a in "${RICE_XDISTRO_ALIASES[@]}"; do
    if [ "$p" = "${a%%|*}" ]; then
      printf '%s' "${a#*|}"
      return 0
    fi
  done
  return 0
}

# non-comment, non-empty lines of an inventory file
rice_pkg_list() { # $1 file
  [ -f "$1" ] || return 0
  grep -v '^[[:space:]]*#' -- "$1" 2>/dev/null | grep -v '^[[:space:]]*$' || true
}

# Generate restore-packages.sh + UNMAPPED.txt.
# $1 (optional) output directory; defaults to $GENERATED_DIR (apply mode).
# In dry-run mode rice-restore.sh passes a temp dir and prints a preview.
rice_restore_packages() {
  local gen=${1:-$GENERATED_DIR}
  mkdir -p -- "$gen"
  local script="$gen/restore-packages.sh" unmapped="$gen/UNMAPPED.txt"
  local fam=$BACKUP_FAMILY tgt=$TARGET_FAMILY

  {
    printf '#!/bin/sh\n'
    printf '# restore-packages.sh - generated by rice-restore on %s\n' "$(date +'%Y-%m-%d %H:%M')"
    printf '# Backup distro family: %s; this machine: %s\n' "$fam" "$tgt"
    printf '# REVIEW EVERY LINE BEFORE RUNNING. rice-restore never runs package\n'
    printf '# managers by itself; only the sudo lines need root.\n\n'
  } > "$script"
  printf '# No known %s -> %s mapping for these package names (names NOT guessed):\n' \
    "$fam" "$tgt" > "$unmapped"

  local osfile=""
  case "$fam" in
    fedora) osfile=packages/fedora-userinstalled.txt ;;
    arch)   osfile=packages/arch-explicit.txt ;;
    ubuntu) osfile=packages/ubuntu-manual.txt ;;
  esac

  local -a pkgs=()
  local pkg mapped_name
  if [ -n "$osfile" ] && [ -f "$osfile" ]; then
    while IFS= read -r pkg; do
      [ -n "$pkg" ] || continue
      if [ "$fam" = "$tgt" ]; then
        pkgs+=("$pkg")
      else
        mapped_name=$(rice_xdistro_map "$pkg")
        if [ -n "$mapped_name" ]; then
          pkgs+=("$mapped_name")
        else
          printf '%s\n' "$pkg" >> "$unmapped"
        fi
      fi
    done < <(rice_pkg_list "$osfile")
  fi
  if [ ${#pkgs[@]} -gt 0 ]; then
    {
      printf '# OS packages'
      [ "$fam" = "$tgt" ] || printf ' (%s names mapped to %s where explicitly known)' "$fam" "$tgt"
      printf '\n'
      case "$tgt" in
        fedora) printf 'sudo dnf install -y %s\n\n' "${pkgs[*]}" ;;
        arch)   printf 'sudo pacman -S --needed %s\n\n' "${pkgs[*]}" ;;
        ubuntu) printf 'sudo apt-get install -y %s\n\n' "${pkgs[*]}" ;;
        *)      printf '# unknown target family (%s); install manually:\n# %s\n\n' "$tgt" "${pkgs[*]}" ;;
      esac
    } >> "$script"
  fi

  # foreign / AUR packages (arch backups)
  if [ "$fam" = "arch" ] && [ -f packages/arch-foreign.txt ]; then
    {
      printf '# AUR / foreign packages (need an AUR helper on an Arch target):\n'
      if [ "$tgt" = "arch" ]; then
        printf '#   yay -S --needed %s\n\n' "$(rice_pkg_list packages/arch-foreign.txt | tr '\n' ' ')"
      else
        printf '#   no automatic mapping to %s; see UNMAPPED.txt\n\n' "$tgt"
        rice_pkg_list packages/arch-foreign.txt >> "$unmapped" || true
      fi
    } >> "$script"
  fi

  # flatpak (cross-distro, user level)
  if [ -s packages/flatpak.txt ]; then
    local app origin
    while IFS=$' \t' read -r app origin; do
      [ -n "$app" ] || continue
      case "$app" in '#'*) continue ;; esac
      printf 'flatpak install --user --noninteractive %s %s\n' "${origin:-flathub}" "$app" >> "$script"
    done < packages/flatpak.txt
    printf '\n' >> "$script"
  fi

  # snap (root level; skip snapd runtime bases that get pulled in automatically)
  if [ -s packages/snap.txt ]; then
    local sn
    while IFS= read -r sn; do
      [ -n "$sn" ] || continue
      case "$sn" in '#'*|Name*|core*|snapd*|bare*|gtk-common-themes*) continue ;; esac
      # shellcheck disable=SC2086  (word-split the columns on purpose)
      set -- $sn
      [ -n "${1:-}" ] && printf 'sudo snap install %s\n' "$1" >> "$script"
    done < packages/snap.txt
    printf '\n' >> "$script"
  fi

  # pip --user
  if [ -s packages/pip-user.txt ]; then
    printf '# Python (pip --user)\n' >> "$script"
    rice_pkg_list packages/pip-user.txt | sed 's/^/python3 -m pip install --user /' >> "$script" || true
    printf '\n' >> "$script"
  fi

  # pipx
  if [ -s packages/pipx.txt ]; then
    printf '# pipx applications\n' >> "$script"
    rice_pkg_list packages/pipx.txt | sed 's/^/pipx install /' >> "$script" || true
    printf '\n' >> "$script"
  fi

  # npm -g
  if [ -s packages/npm-global.txt ]; then
    printf '# global npm packages\n' >> "$script"
    rice_pkg_list packages/npm-global.txt | sed 's/^/npm install -g /' >> "$script" || true
    printf '\n' >> "$script"
  fi

  # cargo
  if [ -s packages/cargo.txt ]; then
    printf '# cargo-installed crates\n' >> "$script"
    rice_pkg_list packages/cargo.txt | sed 's/^/cargo install /' >> "$script" || true
    printf '\n' >> "$script"
  fi

  chmod 755 "$script"
  if ! grep -qv '^[[:space:]]*#' "$unmapped" 2>/dev/null; then
    printf '(none - every package had a mapping)\n' >> "$unmapped"
    printf '[rice-backup] packages: review the generated script %s\n' "$script"
  else
    printf '[rice-backup] packages: review the generated script %s\n' "$script"
    printf '[rice-backup] packages: unmapped names are LISTED in %s\n' "$unmapped"
  fi
  return 0
}

# Copy system/etc/** into the generated dir and write root-actions.sh.
# The script references the STABLE copies (the cloned repo is deleted on exit),
# is meant for review, and is never executed by rice-restore (rule R9).
rice_restore_system() {
  local gen=$GENERATED_DIR
  if [ ! -d system/etc ]; then
    rice_info "system: no /etc content in this backup"
    return 0
  fi
  mkdir -p -- "$gen/system-etc"
  local f rel d
  while IFS= read -r -d '' f; do
    rel=${f#system/etc/}
    d=$(dirname -- "$rel")
    mkdir -p -- "$gen/system-etc/$d"
    cp -a -- "$f" "$gen/system-etc/$rel"
  done < <(find system/etc -type f -print0 2>/dev/null || true)
  {
    printf '#!/bin/sh\n'
    printf '# root-actions.sh - generated by rice-restore on %s\n' "$(date +'%Y-%m-%d %H:%M')"
    printf '# REVIEW EVERY LINE, then run it yourself with:\n'
    printf '#   sudo sh %s/root-actions.sh\n' "$gen"
    printf '# rice-restore never invokes sudo.\n\n'
    while IFS= read -r -d '' f; do
      rel=${f#system/etc/}
      d=$(dirname -- "$rel")
      [ "$d" = "." ] || printf 'mkdir -p -- /etc/%s\n' "$d"
      printf 'cp -a -- %q /etc/%s\n' "$gen/system-etc/$rel" "$rel"
    done < <(find "$gen/system-etc" -type f -print0 2>/dev/null | sort -z)
  } > "$gen/root-actions.sh"
  chmod 755 "$gen/root-actions.sh"
  printf '[rice-backup] system: %s /etc file(s) staged for review; script: %s\n' \
    "$(find "$gen/system-etc" -type f 2>/dev/null | wc -l)" "$gen/root-actions.sh"
  return 0
}

# Recreate the symlink layout recorded by rice-backup (D37, symlinks.tsv).
# Runs inside the cloned repo cwd, AFTER the home sections were restored: for
# every FOLLOWED link, the restored real content moves to the link's recorded
# target location (only when that lands INSIDE the target home) and the
# original symlink is recreated at the link path. Anything that would land
# outside the target home is LISTED in relink-manual.txt, never guessed
# (same philosophy as UNMAPPED.txt). Never runs on dry-run.
rice_restore_relink() {
  if [ ! -f symlinks.tsv ]; then
    rice_info "relink: this backup has no symlinks.tsv (nothing to relink)"
    return 0
  fi
  local gen="$GENERATED_DIR"
  mkdir -p -- "$gen"
  local manual="$gen/relink-manual.txt"
  printf '# Links recorded by rice-backup that could NOT be recreated here\n' > "$manual"
  printf '# rel\traw_target\treason\n' >> "$manual"
  local rel raw _real kind _n _b dirbase dest n=0 m=0
  while IFS=$'\t' read -r rel raw _real kind _n _b; do
    case "$rel" in '#'*) continue ;; esac
    [ -n "$rel" ] || continue
    dirbase=$(dirname -- "$rel")
    # resolve the RAW target against the link's new location (relative raw
    # keeps working because the same relative geometry is recreated)
    dest=""
    case "$raw" in
      /*) dest=$raw ;;
      *)  dest=$(cd -- "$TARGET_HOME/$dirbase" 2>/dev/null \
             && printf '%s/%s' "$(pwd -P)" "$raw" || true) ;;
    esac
    if [ -z "$dest" ] || [ "$dest" = "$TARGET_HOME" ] \
       || [ "${dest#"$TARGET_HOME"/}" = "$dest" ]; then
      printf '%s\t%s\t%s\n' "$rel" "$raw" "target outside the target home" >> "$manual"
      m=$((m + 1)); continue
    fi
    if [ "$dest" = "$TARGET_HOME/$rel" ] || [ "${dest#"$TARGET_HOME/$rel"/}" != "$dest" ]; then
      printf '%s\t%s\t%s\n' "$rel" "$raw" "target is the link path itself" >> "$manual"
      m=$((m + 1)); continue
    fi
    if [ ! -e "$TARGET_HOME/$rel" ] && [ ! -L "$TARGET_HOME/$rel" ]; then
      printf '%s\t%s\t%s\n' "$rel" "$raw" "restored content not found (restore the home sections first)" >> "$manual"
      m=$((m + 1)); continue
    fi
    backup_existing "$dest"
    mkdir -p -- "$(dirname -- "$dest")"
    if mv -- "$TARGET_HOME/$rel" "$dest" 2>/dev/null; then
      ln -sfn -- "$raw" "$TARGET_HOME/$rel"
      n=$((n + 1))
    else
      printf '%s\t%s\t%s\n' "$rel" "$raw" "move failed" >> "$manual"
      m=$((m + 1))
    fi
  done < symlinks.tsv
  printf '[rice-backup] relink: %s link(s) recreated, %s listed in %s\n' "$n" "$m" "$manual"
  return 0
}
